//go:build ignore

// 按实体拆分 Ent mutation，生成过程仍可重复执行。
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path"
	"strconv"
	"strings"
)

// main 保留公共常量，并按各实体的 Mutation 类型拆分方法和依赖。
func main() {
	source, err := os.ReadFile("mutation.go")
	if err != nil { panic(err) }
	set := token.NewFileSet()
	file, err := parser.ParseFile(set, "mutation.go", source, parser.ParseComments)
	if err != nil { panic(err) }
	groups := map[string][]ast.Decl{}
	group := ""
	for _, decl := range file.Decls {
		if gen, ok := decl.(*ast.GenDecl); ok {
			if gen.Tok == token.IMPORT { continue }
			if gen.Tok == token.TYPE {
				if spec, ok := gen.Specs[0].(*ast.TypeSpec); ok && strings.HasSuffix(spec.Name.Name, "Mutation") { group = strings.ToLower(strings.TrimSuffix(spec.Name.Name, "Mutation")) }
			}
		}
		groups[group] = append(groups[group], decl)
	}
	for name, declarations := range groups {
		var body bytes.Buffer
		used := map[string]bool{}
		for _, decl := range declarations {
			ast.Inspect(decl, func(node ast.Node) bool { if selector, ok := node.(*ast.SelectorExpr); ok { if id, ok := selector.X.(*ast.Ident); ok { used[id.Name] = true } }; return true })
			start := decl.Pos()
			switch node := decl.(type) { case *ast.GenDecl: if node.Doc != nil { start = node.Doc.Pos() }; case *ast.FuncDecl: if node.Doc != nil { start = node.Doc.Pos() } }
			body.Write(source[set.Position(start).Offset:set.Position(decl.End()).Offset])
			body.WriteString("\n\n")
		}
		var output bytes.Buffer
		output.WriteString("// Code generated by ent and scripts/split-ent-mutations.go. DO NOT EDIT.\npackage ent\n\nimport (\n")
		for _, imp := range file.Imports {
			value, _ := strconv.Unquote(imp.Path.Value)
			alias := path.Base(value)
			if imp.Name != nil { alias = imp.Name.Name }
			if used[alias] { output.WriteString(string(source[set.Position(imp.Pos()).Offset:set.Position(imp.End()).Offset])+"\n") }
		}
		output.WriteString(")\n\n")
		output.Write(body.Bytes())
		formatted, err := format.Source(output.Bytes())
		if err != nil { panic(err) }
		target := "mutation.go"
		if name != "" { target = "mutation_"+name+".go" }
		if bytes.Count(formatted, []byte("\n")) >= 1000 { panic(fmt.Sprintf("%s exceeds file limit", target)) }
		if err := os.WriteFile(target, formatted, 0o644); err != nil { panic(err) }
	}
}
