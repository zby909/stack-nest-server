// split-generated 按语义拆分传输方法和 Docker 模型，保持生成代码单文件小于 1000 行。
package main

import (
	"bytes"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
)

// main 仅移动指定的生成方法，保留路由注册、参数解析和生成器注释。
func main() {
	path := "../internal/generated/server.gen.go"
	source, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	set := token.NewFileSet()
	file, err := parser.ParseFile(set, path, source, parser.ParseComments)
	if err != nil {
		panic(err)
	}
	names := map[string]bool{"ListApps": true, "CreateApp": true, "GetApp": true, "UpdateApp": true, "OperateApp": true, "GetAppLogs": true, "GetAppDeploymentLogs": true, "CreateUpload": true, "GetUpload": true, "AppendUpload": true, "DeleteUpload": true, "CompleteUpload": true, "ListProjectFiles": true, "PublishDraft": true, "DiscardDraft": true, "ListProjectChanges": true}
	var primary, transfers bytes.Buffer
	transfers.WriteString("//go:build go1.22\n\n// Code generated by oapi-codegen and scripts/split-generated.go. DO NOT EDIT.\npackage generated\n\nimport (\"errors\"; \"fmt\"; \"net/http\"; \"github.com/oapi-codegen/runtime\")\n\n")
	last, moved := 0, 0
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if !ok || function.Recv == nil || !names[function.Name.Name] {
			continue
		}
		start := set.Position(function.Pos()).Offset
		if function.Doc != nil {
			start = set.Position(function.Doc.Pos()).Offset
		}
		end := set.Position(function.End()).Offset
		primary.Write(source[last:start])
		transfers.Write(source[start:end])
		transfers.WriteString("\n\n")
		last, moved = end, moved+1
	}
	if moved != len(names) {
		panic("generated operation set changed; inspect split configuration")
	}
	primary.Write(source[last:])
	for target, content := range map[string][]byte{path: primary.Bytes(), "../internal/generated/transfers.gen.go": transfers.Bytes()} {
		formatted, err := format.Source(content)
		if err != nil {
			panic(err)
		}
		if err := os.WriteFile(target, formatted, 0o644); err != nil {
			panic(err)
		}
	}
	splitAppModels()
}

// splitAppModels 将 Docker 应用模型、枚举和枚举校验一起移入独立生成文件。
func splitAppModels() {
	path := "../internal/generated/models.gen.go"
	source, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	set := token.NewFileSet()
	file, err := parser.ParseFile(set, path, source, parser.ParseComments)
	if err != nil {
		panic(err)
	}
	names := map[string]bool{
		"AppDetail": true, "AppInput": true, "AppList": true, "AppProgress": true, "AppProgressStage": true,
		"AppRuntime": true, "AppRuntimeHealth": true, "AppRuntimeHealthCheck": true,
		"AppDiskUsage": true, "AppDiskArea": true, "AppDiskAreaSource": true, "AppUsage": true, "AppView": true, "ContainerApp": true, "ContainerAppStatus": true,
	}
	var primary, apps bytes.Buffer
	apps.WriteString("// Code generated by oapi-codegen and scripts/split-generated.go. DO NOT EDIT.\npackage generated\n\nimport \"time\"\n\n")
	last, movedTypes := 0, 0
	for _, declaration := range file.Decls {
		move := false
		start := set.Position(declaration.Pos()).Offset
		switch d := declaration.(type) {
		case *ast.GenDecl:
			if d.Doc != nil {
				start = set.Position(d.Doc.Pos()).Offset
			}
			for _, spec := range d.Specs {
				switch value := spec.(type) {
				case *ast.TypeSpec:
					if names[value.Name.Name] {
						move = true
						movedTypes++
					}
				case *ast.ValueSpec:
					if valueType, ok := value.Type.(*ast.Ident); ok && names[valueType.Name] {
						move = true
					}
				}
			}
		case *ast.FuncDecl:
			if d.Doc != nil {
				start = set.Position(d.Doc.Pos()).Offset
			}
			if d.Recv != nil && len(d.Recv.List) == 1 {
				if receiver, ok := d.Recv.List[0].Type.(*ast.Ident); ok {
					move = names[receiver.Name]
				}
			}
		}
		if !move {
			continue
		}
		end := set.Position(declaration.End()).Offset
		primary.Write(source[last:start])
		apps.Write(source[start:end])
		apps.WriteString("\n\n")
		last = end
	}
	if movedTypes != len(names) {
		panic("generated Docker models changed; inspect split configuration")
	}
	primary.Write(source[last:])
	for target, content := range map[string][]byte{path: primary.Bytes(), "../internal/generated/apps.gen.go": apps.Bytes()} {
		formatted, err := format.Source(content)
		if err != nil {
			panic(err)
		}
		if bytes.Count(formatted, []byte("\n")) > 1000 {
			panic("generated model exceeds 1000 lines")
		}
		if err := os.WriteFile(target, formatted, 0o644); err != nil {
			panic(err)
		}
	}
}
